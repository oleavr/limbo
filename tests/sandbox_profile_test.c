#define OPERATIONS    204
#define NODES         3
#define NODES_AT      (16 + 2 * OPERATIONS)
#define PATTERN_AT    (NODES_AT + 8 * NODES)
#define MATCH_AT      (NODES_AT + 4)
#define UNMATCH_AT    (NODES_AT + 6)
#define ARGUMENT_AT   (NODES_AT + 2)
#define SKIP_PAST_MAX 16

static void check_parsed(void);
