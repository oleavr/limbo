#include <pthread.h>
#include <sys/resource.h>

#include "check.h"

static void *other_thread(void *unused);

int
main(void)
{
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS)
			== IOPOL_MATERIALIZE_DATALESS_FILES_ON);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_THREAD)
			== IOPOL_MATERIALIZE_DATALESS_FILES_DEFAULT);

	CHECK(setiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_THREAD,
			      IOPOL_MATERIALIZE_DATALESS_FILES_OFF)
			== 0);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_THREAD)
			== IOPOL_MATERIALIZE_DATALESS_FILES_OFF);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS)
			== IOPOL_MATERIALIZE_DATALESS_FILES_ON);

	CHECK(setiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS,
			      IOPOL_MATERIALIZE_DATALESS_FILES_OFF)
			== 0);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS)
			== IOPOL_MATERIALIZE_DATALESS_FILES_OFF);
	pthread_t thread;
	CHECK(pthread_create(&thread, NULL, other_thread, NULL) == 0);
	CHECK(pthread_join(thread, NULL) == 0);

	CHECK(setiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_THREAD,
			      IOPOL_MATERIALIZE_DATALESS_FILES_ON)
			== 0);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_THREAD)
			== IOPOL_MATERIALIZE_DATALESS_FILES_ON);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS)
			== IOPOL_MATERIALIZE_DATALESS_FILES_OFF);

	CHECK(setiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS,
			      IOPOL_MATERIALIZE_DATALESS_FILES_ON)
			== 0);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS)
			== IOPOL_MATERIALIZE_DATALESS_FILES_ON);
	CHECK(setiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS,
			      IOPOL_MATERIALIZE_DATALESS_FILES_DEFAULT)
			== 0);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS)
			== IOPOL_MATERIALIZE_DATALESS_FILES_OFF);
	return 0;
}

static void *
other_thread(void *unused)
{
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_THREAD)
			== IOPOL_MATERIALIZE_DATALESS_FILES_DEFAULT);
	CHECK(getiopolicy_np(IOPOL_TYPE_VFS_MATERIALIZE_DATALESS_FILES,
			      IOPOL_SCOPE_PROCESS)
			== IOPOL_MATERIALIZE_DATALESS_FILES_OFF);
	return NULL;
}
